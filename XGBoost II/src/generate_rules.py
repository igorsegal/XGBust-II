import json
import os
from pathlib import Path

def load_passed_edges(path: str = 'data/passed_edges.jsonl') -> list:
    """
    Load PASS-ed edges from JSONL file.
    Each line is a JSON object with verdict=='PASS'.
    """
    if not Path(path).exists():
        print(f'⚠️  File {path} not found. Returning empty list.')
        return []

    edges = []
    with open(path, 'r', encoding='utf-8') as f:
        for i, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                obj = json.loads(line)
                if obj.get('verdict') == 'PASS':
                    edges.append(obj)
                else:
                    print(f'ℹ️  Skipped line {i}: verdict != PASS')
            except json.JSONDecodeError as e:
                print(f'❌ JSON decode error at line {i}: {e}')
    return edges

def generate_mql5_rules(
    input_path: str = 'data/passed_edges.jsonl',
    output_path: str = 'rules/mql5_signals.mqh'
):
    """
    Generate MQL5 header file with check_edge_signal() function.
    """
    # Ensure output directory exists
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)

    edges = load_passed_edges(input_path)
    if not edges:
        print(f'⚠️  No PASS-ed edges found in {input_path}. Generating stub.')
        rules = [
            '   // ⚠️  No valid signals loaded. Always returns false.',
            '   return false;',
        ]
    else:
        print(f'✅ Loaded {len(edges)} PASS-ed signal(s).')
        rules = []
        for i, edge in enumerate(edges, 1):
            url = edge.get('url', 'N/A')
            title = edge.get('title', 'Untitled')
            year = edge.get('published_year', 'unknown')
            formula = edge.get('formula_and_logic', '').replace('\n', ' ').strip()[:120] + '...'
            pairs = ', '.join(edge.get('forex_pairs', ['EURUSD']))
            tf = ', '.join(edge.get('timeframes', ['H1']))

            rules.append(f'   // Signal #{i} — {title} ({year})')
            rules.append(f'   // URL: {url}')
            rules.append(f'   // Logic: {formula}')
            rules.append(f'   // Pairs: [{pairs}] | TF: [{tf}]')
            rules.append('   // TODO: Implement actual logic here (e.g., indicator checks)')
            rules.append('   // → This is a template. Replace with real C++/MQL5 code.')
            if i == 1:
                rules.append('   if (true) {')
            else:
                rules.append('   } else if (true) {')
        rules.append('   } else {')
        rules.append('      return false;')
        rules.append('   }')

    # Write final file
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('// MQL5 Trading Rules (auto-generated by XGBoost-edge)\n\n')
        f.write('#property strict\n\n')
        f.write('bool check_edge_signal() {\n')
        if rules:
            f.writelines(line + '\n' for line in rules)
        else:
            f.write('   return false;\n')
        f.write('}\n')

    print(f'✅ Generated: {output_path}')


def main():
    generate_mql5_rules()

if __name__ == '__main__':
    main()
